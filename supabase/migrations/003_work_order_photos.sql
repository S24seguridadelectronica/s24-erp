-- ============================================================================
-- 003 — Evidencias fotográficas por orden de trabajo
-- ============================================================================
-- Cada trabajo ejecutado puede guardar varias fotos con su descripción.
-- El historial del cliente se arma con sus órdenes + estas evidencias.
--
-- Ejecutar en: Supabase Dashboard → SQL Editor → Run
-- Es idempotente: se puede ejecutar varias veces sin error.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.work_order_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id BIGINT NOT NULL REFERENCES public.work_orders(id) ON DELETE CASCADE,
  caption TEXT,
  photo TEXT NOT NULL,
  created_by UUID REFERENCES public.profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS work_order_photos_order_idx
  ON public.work_order_photos (work_order_id);

ALTER TABLE public.work_order_photos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "wo_photos_select" ON public.work_order_photos;
CREATE POLICY "wo_photos_select" ON public.work_order_photos
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "wo_photos_insert" ON public.work_order_photos;
CREATE POLICY "wo_photos_insert" ON public.work_order_photos
  FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "wo_photos_update" ON public.work_order_photos;
CREATE POLICY "wo_photos_update" ON public.work_order_photos
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "wo_photos_delete" ON public.work_order_photos;
CREATE POLICY "wo_photos_delete" ON public.work_order_photos
  FOR DELETE TO authenticated USING (true);

NOTIFY pgrst, 'reload schema';

